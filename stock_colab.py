    def _clean_ticker(self, ticker):
        """
        국장/미장 혼합 모드 자산 분기 스캔 규칙 알고리즘 (.KS / .KQ 자동 지정)
        """
        if ticker.isdigit() and len(ticker) == 6:
            if self.select_mode == "4. 코스닥":
                return f"{ticker}.KQ"
            elif self.select_mode == "3. 코스피":
                return f"{ticker}.KS"
            else:
                kosdaq_master_list = ["247540", "086520", "293490", "066970", "191410", "403000", "214150", "039200", "028300"]
                if ticker in kosdaq_master_list:
                    return f"{ticker}.KQ"
                return f"{ticker}.KS"
        return ticker

    def _get_scalar(self, val):
        if isinstance(val, pd.Series) or isinstance(val, np.ndarray):
            return float(val.iloc[-1]) if len(val) > 0 else 0.0
        return float(val)

    def stage0_macro_filter(self):
        print(f"\n📡 [Stage 0] 글로벌 거시 경제 통합 필터 가동 (기준일: {datetime.now().strftime('%Y-%m-%d')})")
