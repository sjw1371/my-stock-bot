    def stage1_2_sepa_analysis(self):
        print(f"🔍 [Stage 1-2] 트렌드 템플릿 8대 조건 검증 & SEPA VCP 통계 분석 중...")
        results = []

        try:
            bm_df = yf.Ticker('^GSPC').history(period='1y')
            bm_close = bm_df['Close']
        except:
            bm_close = None

        for idx, ticker in enumerate(self.raw_tickers):
            search_ticker = self._clean_ticker(ticker)
            try:
                tk_obj = yf.Ticker(search_ticker)
                df = tk_obj.history(period='1y')

                if df.empty or len(df) < 200:
                    results.append(self._get_fallback_data(ticker))
                    continue

                curr_price = df['Close'].iloc[-1]

                df['MA50'] = df['Close'].rolling(50).mean()
                df['MA150'] = df['Close'].rolling(150).mean()
                df['MA200'] = df['Close'].rolling(200).mean()

                ma50 = df['MA50'].iloc[-1]
                ma150 = df['MA150'].iloc[-1]
                ma200 = df['MA200'].iloc[-1]
                ma200_1m_ago = df['MA200'].iloc[-22] if len(df) >= 22 else ma200

                high_52wk = df['High'].tail(252).max()
                low_52wk = df['Low'].tail(252).min()

                c1 = (curr_price > ma150) and (curr_price > ma200)
                c2 = ma150 > ma200
                c3 = ma200 > ma200_1m_ago
                c4 = (ma50 > ma150) and (ma50 > ma200)
                c5 = curr_price >= (low_52wk * 1.25)
                c6 = curr_price >= (high_52wk * 0.75)

                c7 = False
                if bm_close is not None and len(bm_close) >= len(df):
                    rs_series = df['Close'] / bm_close.reindex(df.index).ffill()
                    rs_curr = rs_series.iloc[-1]
                    rs_6wk_ago = rs_series.iloc[-30] if len(rs_series) >= 30 else rs_curr
                    c7 = rs_curr > rs_6wk_ago
                else:
                    c7 = True

                c8 = curr_price > ma50

                trend_template_pass = all([c1, c2, c3, c4, c5, c6, c7, c8])
                passed_conditions_count = sum([c1, c2, c3, c4, c5, c6, c7, c8])

                vol_recent = (df['High'].tail(20).max() - df['Low'].tail(20).min()) / curr_price
                vol_past = (df['High'].tail(60).iloc[:-20].max() - df['Low'].tail(60).iloc[:-20].min()) / curr_price if len(df) >= 60 else vol_recent
                is_vcp_pattern = (vol_recent < (vol_past * 0.65)) if vol_past > 0 else False

                df['MA20'] = df['Close'].rolling(20).mean()
                df['MA60'] = df['Close'].rolling(60).mean()
                ma20_curr = df['MA20'].iloc[-1]
                ma60_curr = df['MA60'].iloc[-1]

                disp_20 = ((curr_price - ma20_curr) / ma20_curr) * 100 if ma20_curr > 0 else 0.0

                high_low = df['High'] - df['Low']
                high_cp = np.abs(df['High'] - df['Close'].shift())
                low_cp = np.abs(df['Low'] - df['Close'].shift())
                df['ATR'] = pd.concat([high_low, high_cp, low_cp], axis=1).max(axis=1).rolling(14).mean()
                curr_atr = df['ATR'].iloc[-1]

                df['Vol_MA20'] = df['Volume'].rolling(20).mean()
                vol_ratio = (df['Volume'].iloc[-1] / df['Vol_MA20'].iloc[-1]) if (len(df) > 20 and df['Vol_MA20'].iloc[-1] > 0) else 1.0

                df['Returns'] = df['Close'].pct_change()
                wins = df['Returns'][df['Returns'] > 0]
                losses = df['Returns'][df['Returns'] < 0]

                win_rate = len(wins) / len(df['Returns'].dropna()) if len(df['Returns'].dropna()) > 0 else 0.45
                payoff_ratio = abs(wins.mean() / losses.mean()) if not losses.empty and losses.mean() != 0 else 1.2

                kelly_f = win_rate - ((1 - win_rate) / payoff_ratio) if payoff_ratio > 0 else 0.0

                recommended_weight = max(0.04, kelly_f * 0.5) if trend_template_pass else 0.02

                results.append({
                    '티커': ticker, '현재가': curr_price, '피벗거리(%)': round(disp_20, 2),
                    '승률': win_rate, '손익비': payoff_ratio, '켈리비중': recommended_weight,
                    'ATR': curr_atr, '거래량배수': vol_ratio, 'VCP패턴': is_vcp_pattern,
                    'MA20': ma20_curr, 'MA60': ma60_curr,
                    '트렌드_템플릿': "✅ PASS" if trend_template_pass else f"⚠️ {passed_conditions_count}/8"
                })
            except:
                results.append(self._get_fallback_data(ticker))

        self.pipeline_df = pd.DataFrame(results)
        print(f"   - [연동 성공] 트렌드 템플릿 8대 검증 완수: 총 {len(self.pipeline_df)}개 후보군 적재\n")

